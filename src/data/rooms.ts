export function getAllRooms(): Room[] {
  return ROOMS_DATA
}

export function getRoomById(id: string): Room | undefined {
  return ROOMS_DATA.find((r) => r.id === id || r.roomNumber === id)
}

export function getAdjacentRooms(currentId: string): {
  prevRoom: Room
  nextRoom: Room
} {
  const currentIndex = ROOMS_DATA.findIndex((r) => r.id === currentId || r.roomNumber === currentId)
  const safeIndex = currentIndex === -1 ? 0 : currentIndex

  const prevIndex = (safeIndex - 1 + ROOMS_DATA.length) % ROOMS_DATA.length
  const nextIndex = (safeIndex + 1) % ROOMS_DATA.length

  return {
    prevRoom: ROOMS_DATA[prevIndex],
    nextRoom: ROOMS_DATA[nextIndex],
  }
}

export function getSpaceById(room: Room, spaceId: string): Space | undefined {
  return room.spaces[spaceId]
}
